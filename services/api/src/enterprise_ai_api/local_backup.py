"""Encrypted local SQLite + original-file backups, verified before isolated restoration.

No HTTP endpoint, cloud service, subprocess or automatic replacement of live data.
Archives are bounded to 128 MiB of content for small local pilots.
"""

import argparse
import base64
import hashlib
import hmac
import io
import json
import os
import sqlite3
import zipfile
from contextlib import closing
from datetime import UTC, datetime
from pathlib import Path
from uuid import UUID

from cryptography.hazmat.primitives.ciphers.aead import AESGCM

from enterprise_ai_api.crypto import ENCRYPTED_PREFIX, FILE_MAGIC
from enterprise_ai_api.database import PROJECT_ROOT

MAGIC = b"EAKL1"
CONTEXT = b"enterprise-ai:local-backup:v1"
MAX_CONTENT = 128 * 1024 * 1024
MAX_ARCHIVE = MAX_CONTENT + 8 * 1024 * 1024
MAX_FILES = 10000


class LocalBackupError(RuntimeError):
    pass


def read_bounded(path: Path, limit: int = MAX_ARCHIVE) -> bytes:
    if not path.is_file() or path.is_symlink():
        raise LocalBackupError("Required regular file is missing or is a symbolic link")
    with path.open("rb") as source:
        payload = source.read(limit + 1)
    if len(payload) > limit:
        raise LocalBackupError("Local backup size limit exceeded (128 MiB content)")
    return payload


def write_new(path: Path, payload: bytes) -> None:
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, "wb") as output:
        output.write(payload)
        output.flush()
        os.fsync(output.fileno())


def read_key(path: Path) -> bytes:
    key = read_bounded(path, 32)
    if len(key) != 32:
        raise LocalBackupError("Backup key must be the separate 32-byte key generated by keygen")
    return key


def decrypt_original(payload: bytes, key: bytes, context: bytes) -> bytes:
    if not payload.startswith(FILE_MAGIC):
        raise LocalBackupError("Original file is not in the authenticated encryption format")
    offset = len(FILE_MAGIC)
    return AESGCM(key).decrypt(payload[offset : offset + 12], payload[offset + 12 :], context)


def validate_contents(files: dict[str, bytes]) -> dict[str, int]:
    """Check SQLite integrity, all encrypted fields, and every referenced original file."""
    try:
        master = files["master.key"].decode().strip().encode()
        if len(master) < 32:
            raise LocalBackupError("Application master key is invalid")
        aes_key = hmac.new(master, b"enterprise-ai:aes-256-gcm", hashlib.sha256).digest()
        hash_key = hmac.new(master, b"enterprise-ai:content-fingerprint", hashlib.sha256).digest()
        with closing(sqlite3.connect(":memory:")) as database:
            try:
                database.deserialize(files["enterprise.db"])
                database.execute("PRAGMA trusted_schema=OFF")
                database.execute("PRAGMA query_only=ON")
                if database.execute("PRAGMA integrity_check").fetchall() != [("ok",)]:
                    raise LocalBackupError("SQLite integrity check failed")
                if database.execute("PRAGMA foreign_key_check").fetchone():
                    raise LocalBackupError("SQLite foreign key check failed")
                if not database.execute("SELECT version_num FROM alembic_version").fetchone():
                    raise LocalBackupError("Database migration version is missing")
                tables = [
                    row[0]
                    for row in database.execute("SELECT name FROM sqlite_master WHERE type='table'")
                ]
                # Detect the wrong master key even when there are no uploaded originals yet.
                for table in tables:
                    quoted = table.replace('"', '""')
                    for row in database.execute(f'SELECT * FROM "{quoted}"'):
                        for value in row:
                            if isinstance(value, str) and value.startswith(ENCRYPTED_PREFIX):
                                ciphertext = base64.urlsafe_b64decode(
                                    value.removeprefix(ENCRYPTED_PREFIX)
                                )
                                decrypt_original(ciphertext, aes_key, b"database-field:v1")
                expected = {"enterprise.db", "master.key"}
                count = 0
                for tenant, document, version, key, size, fingerprint in database.execute(
                    "SELECT tenant_id, document_id, id, object_key, byte_size, content_hash "
                    "FROM document_versions"
                ):
                    ids = [str(UUID(value)) for value in (tenant, document, version)]
                    if key != "/".join([*ids, "payload.enc"]):
                        raise LocalBackupError("Unexpected document storage key")
                    name = f"uploads/{key}"
                    expected.add(name)
                    raw = decrypt_original(files[name], aes_key, ":".join(ids).encode())
                    if len(raw) != size or not hmac.compare_digest(
                        hmac.new(hash_key, raw, hashlib.sha256).hexdigest(), fingerprint
                    ):
                        raise LocalBackupError("Original file verification failed")
                    count += 1
                if set(files) != expected:
                    raise LocalBackupError("Backup contains unexpected or missing files")
                return {"original_files": count, "files": len(files)}
            finally:
                database.close()
    except LocalBackupError:
        raise
    except Exception as error:
        raise LocalBackupError(
            "Database, encryption key or original files could not be verified"
        ) from error


def snapshot(source: Path) -> dict[str, bytes]:
    if source.is_symlink():
        raise LocalBackupError("Source directory must not be a symbolic link")
    source = source.resolve(strict=True)
    db_path = source / "enterprise.db"
    if db_path.is_symlink() or not db_path.is_file():
        raise LocalBackupError("Existing local AI SQLite database is required")
    if (
        db_path.stat().st_size
        + (Path(f"{db_path}-wal").stat().st_size if Path(f"{db_path}-wal").exists() else 0)
        > MAX_CONTENT
    ):
        raise LocalBackupError("Source database exceeds the local backup size limit")
    files = {"master.key": read_bounded(source / "master.key", 4096)}
    with closing(sqlite3.connect(db_path.as_uri() + "?mode=ro", uri=True)) as database:
        try:
            with closing(sqlite3.connect(":memory:")) as copy:
                try:
                    database.backup(copy)
                    snapshot_bytes = copy.serialize()
                    # SQLite's backup API includes committed WAL pages. Only normalize the
                    # copied header, never the source: deserialize cannot reopen WAL images.
                    # https://www.sqlite.org/c3ref/deserialize.html
                    files["enterprise.db"] = snapshot_bytes[:18] + b"\x01\x01" + snapshot_bytes[20:]
                    keys = [
                        row[0] for row in copy.execute("SELECT object_key FROM document_versions")
                    ]
                finally:
                    copy.close()
        finally:
            database.close()
    total = sum(map(len, files.values()))
    if total > MAX_CONTENT or len(keys) + 2 > MAX_FILES:
        raise LocalBackupError("Local backup size/file-count limit exceeded")
    for key in keys:
        # Keys must be canonical UUID paths, not arbitrary database-controlled paths.
        parts = key.split("/")
        if (
            len(parts) != 4
            or parts[-1] != "payload.enc"
            or any(str(UUID(value)) != value for value in parts[:3])
        ):
            raise LocalBackupError("Unexpected document storage key")
        name = f"uploads/{key}"
        path = source / name
        if path.resolve() != path or path.is_symlink():
            raise LocalBackupError("Original file path contains a symbolic link")
        files[name] = read_bounded(path, min(11 * 1024 * 1024, MAX_CONTENT - total))
        total += len(files[name])
    validate_contents(files)
    return files


def create_local_backup(source: Path, output: Path, key_file: Path) -> dict[str, int]:
    key = read_key(key_file)
    if output.exists():
        raise LocalBackupError("Backup output already exists; choose a new filename")
    files = snapshot(source)
    manifest = {
        "format": 1,
        "created_at": datetime.now(UTC).isoformat(),
        "sha256": {name: hashlib.sha256(data).hexdigest() for name, data in files.items()},
    }
    stream = io.BytesIO()
    with zipfile.ZipFile(stream, "w", compression=zipfile.ZIP_STORED) as archive:
        for name, data in files.items():
            archive.writestr(name, data)
        archive.writestr("manifest.json", json.dumps(manifest).encode())
    nonce = os.urandom(12)
    encrypted = MAGIC + nonce + AESGCM(key).encrypt(nonce, stream.getvalue(), CONTEXT)
    # Read back and fully verify in memory before publishing any backup file.
    verify_archive(encrypted, key)
    write_new(output, encrypted)
    return {"original_files": len(files) - 2, "encrypted_bytes": len(encrypted)}


def verify_archive(encrypted: bytes, key: bytes) -> dict[str, bytes]:
    try:
        if not encrypted.startswith(MAGIC) or len(encrypted) > MAX_ARCHIVE:
            raise LocalBackupError("Invalid or oversized local backup")
        offset = len(MAGIC)
        raw = AESGCM(key).decrypt(
            encrypted[offset : offset + 12], encrypted[offset + 12 :], CONTEXT
        )
        with zipfile.ZipFile(io.BytesIO(raw)) as archive:
            entries = archive.infolist()
            names = [item.filename for item in entries]
            if (
                len(names) > MAX_FILES + 1
                or len(set(names)) != len(names)
                or any(
                    item.is_dir() or item.compress_type != zipfile.ZIP_STORED for item in entries
                )
                or sum(item.file_size for item in entries) > MAX_ARCHIVE
            ):
                raise LocalBackupError("Invalid archive entries or size")
            manifest = json.loads(archive.read("manifest.json"))
            if manifest.get("format") != 1 or not isinstance(manifest.get("sha256"), dict):
                raise LocalBackupError("Invalid backup manifest")
            if set(names) != {*manifest["sha256"], "manifest.json"}:
                raise LocalBackupError("Archive and manifest do not match")
            files = {name: archive.read(name) for name in manifest["sha256"]}
            if sum(map(len, files.values())) > MAX_CONTENT:
                raise LocalBackupError("Local backup content is too large")
            for name, content in files.items():
                if hashlib.sha256(content).hexdigest() != manifest["sha256"][name]:
                    raise LocalBackupError("Backup file checksum mismatch")
        validate_contents(files)
        return files
    except LocalBackupError:
        raise
    except Exception as error:
        raise LocalBackupError(
            "Backup authentication or validation failed; check the backup key"
        ) from error


def restore_local_backup(archive: Path, key_file: Path, target: Path) -> dict[str, int]:
    # Validate everything before creating any target; never overwrite a live installation.
    if target.exists() or target.is_symlink():
        raise LocalBackupError(
            "Restore target must be a new directory; existing data is never replaced"
        )
    files = verify_archive(read_bounded(archive), read_key(key_file))
    target.mkdir(mode=0o700)
    for name, data in files.items():
        path = target / name
        path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        write_new(path, data)
    return {"original_files": len(files) - 2, "files": len(files)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    keygen = commands.add_parser("keygen")
    keygen.add_argument("--key-file", type=Path, required=True)
    create = commands.add_parser("create")
    create.add_argument("--key-file", type=Path, required=True)
    create.add_argument("--source", type=Path, default=PROJECT_ROOT / "data/local/ollama")
    create.add_argument("--output", type=Path, required=True)
    for name in ("verify", "restore"):
        command = commands.add_parser(name)
        command.add_argument("--key-file", type=Path, required=True)
        command.add_argument("--archive", type=Path, required=True)
        if name == "restore":
            command.add_argument("--target", type=Path, required=True)
    args = parser.parse_args()
    try:
        if args.command == "keygen":
            write_new(args.key_file, os.urandom(32))
            result = {"backup_key_created": True}
        elif args.command == "create":
            result = create_local_backup(args.source, args.output, args.key_file)
        elif args.command == "verify":
            files = verify_archive(read_bounded(args.archive), read_key(args.key_file))
            result = {"verified": True, "original_files": len(files) - 2}
        else:
            result = restore_local_backup(args.archive, args.key_file, args.target)
        print(json.dumps(result))
    except (OSError, ValueError, sqlite3.Error, LocalBackupError):
        # Paths, database errors and input bytes can contain sensitive data.
        parser.exit(
            1,
            "操作失败：检查文件、备份密钥、空间及目录权限；原件必须完整，目标不能已存在。\n"
            "若恢复写入中断，保留原数据并改用新的恢复目录重试。\n",
        )


if __name__ == "__main__":
    main()
